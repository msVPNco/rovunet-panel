// Package migrate moves a server installed under the panel's pre-rename
// (SlipGate-era) names onto the current Rovunet names, in place: the config
// directory, system users and groups, systemd units, sshd_config blocks,
// systemd-resolved drop-ins, iptables boot files and the binary itself.
//
// It runs once, from the new binary's first post-update (which the old
// binary's own updater starts) or any later root invocation, and is a no-op
// once /etc/rovunet exists. User and group renames keep their UIDs/GIDs, so
// file ownership and live per-UID firewall rules stay valid.
package migrate

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/msVPNco/rovunet-panel/internal/config"
	"github.com/msVPNco/rovunet-panel/internal/system"
)

// The legacy name is assembled so a repo-wide rename never rewrites it.
var legacy = "slip" + "gate"

// Paths are variables so tests can point them at a temporary tree.
var (
	OldConfigDir = "/etc/" + legacy
	NewConfigDir = config.DefaultConfigDir
	SystemdDir   = "/etc/systemd/system"
	ResolvedDir  = "/etc/systemd/resolved.conf.d"
	IptablesDir  = "/etc/iptables"
	BinDir       = config.DefaultBinDir
)

// Logger receives one line per step.
type Logger func(string)

// Needed reports whether this server still has a pre-rename install.
func Needed() bool {
	if _, err := os.Stat(OldConfigDir); err != nil {
		return false
	}
	_, err := os.Stat(NewConfigDir)
	return os.IsNotExist(err)
}

// RenamePaths rewrites only the panel's own directory paths. It is what
// config.json and Caddyfiles get: they also hold user passwords, which a
// broader rewrite could alter.
func RenamePaths(s string) string {
	return strings.NewReplacer(
		"/etc/"+legacy+"/", "/etc/rovunet/",
		"/etc/"+legacy+"\"", "/etc/rovunet\"",
	).Replace(s)
}

// Rename also maps the binary, unit, account and file names. It is applied
// to systemd units, WARP's wg0.conf and boot files, which carry those names
// and no user passwords (the SOCKS unit's --creds is regenerated by
// post-update right after, from config.json).
func Rename(s string) string {
	return strings.NewReplacer(
		"/etc/"+legacy, "/etc/rovunet",
		"/usr/local/bin/"+legacy, "/usr/local/bin/rovunet",
		legacy+"-", "rovunet-",
		"User="+legacy+"\n", "User=rovunet\n",
		"Group="+legacy+"\n", "Group=rovunet\n",
	).Replace(s)
}

// Run performs the migration. Nothing is attempted unless Needed.
func Run(log Logger) error {
	if !Needed() {
		return nil
	}
	if os.Geteuid() != 0 {
		return fmt.Errorf("migrating %s to %s needs root: run with sudo", OldConfigDir, NewConfigDir)
	}
	log("Migrating this server from the old panel names to Rovunet...")

	units, err := legacyUnits()
	if err != nil {
		return err
	}
	wasActive := make(map[string]bool)
	wasEnabled := make(map[string]bool)
	for _, u := range units {
		wasActive[u] = run("systemctl", "is-active", "--quiet", u+".service") == nil
		wasEnabled[u] = run("systemctl", "is-enabled", "--quiet", u+".service") == nil
		_ = run("systemctl", "stop", u+".service")
		_ = run("systemctl", "disable", u+".service")
	}

	renameAccounts(log)

	if err := os.Rename(OldConfigDir, NewConfigDir); err != nil {
		return fmt.Errorf("move %s: %w", OldConfigDir, err)
	}
	log("  " + OldConfigDir + " → " + NewConfigDir)
	if err := rewriteTextFiles(NewConfigDir); err != nil {
		return err
	}

	for _, u := range units {
		if err := moveUnit(u); err != nil {
			log(fmt.Sprintf("  Warning: unit %s: %v", u, err))
		}
	}
	// Units now exec /usr/local/bin/rovunet: put it there before starting them.
	if err := moveBinary(); err != nil {
		log("  Warning: binary: " + err.Error())
	}
	_ = run("systemctl", "daemon-reload")
	for _, u := range units {
		n := Rename(u)
		if wasEnabled[u] {
			_ = run("systemctl", "enable", n+".service")
		}
		if wasActive[u] {
			if err := run("systemctl", "start", n+".service"); err != nil {
				log(fmt.Sprintf("  Warning: %s did not start: %v", n, err))
			}
		}
	}
	log(fmt.Sprintf("  %d systemd service(s) renamed", len(units)))

	for _, dir := range []string{ResolvedDir, IptablesDir} {
		if err := renameFiles(dir); err != nil {
			log(fmt.Sprintf("  Warning: %s: %v", dir, err))
		}
	}
	_ = run("systemctl", "try-restart", "systemd-resolved")

	if err := migrateSSHConfig(); err != nil {
		log("  Warning: sshd_config: " + err.Error())
	}
	log("Migration complete: the command is now 'rovunet'")
	return nil
}

// legacyUnits lists the panel's units under their old prefix.
func legacyUnits() ([]string, error) {
	entries, err := os.ReadDir(SystemdDir)
	if err != nil {
		return nil, err
	}
	var units []string
	for _, e := range entries {
		n := e.Name()
		if strings.HasPrefix(n, legacy+"-") && strings.HasSuffix(n, ".service") {
			units = append(units, strings.TrimSuffix(n, ".service"))
		}
	}
	return units, nil
}

// moveUnit rewrites a unit (paths, binary, users) under its new name.
func moveUnit(name string) error {
	oldPath := filepath.Join(SystemdDir, name+".service")
	data, err := os.ReadFile(oldPath)
	if err != nil {
		return err
	}
	newPath := filepath.Join(SystemdDir, Rename(name)+".service")
	if err := os.WriteFile(newPath, []byte(Rename(string(data))), 0644); err != nil {
		return err
	}
	return os.Remove(oldPath)
}

// renameAccounts renames the panel's users and groups in place.
func renameAccounts(log Logger) {
	for _, suffix := range []string{"", "-ssh", "-socks", "-naive"} {
		oldName, newName := legacy+suffix, "rovunet"+suffix
		if run("id", "-u", oldName) == nil {
			if err := run("usermod", "-l", newName, oldName); err != nil {
				log(fmt.Sprintf("  Warning: rename user %s: %v", oldName, err))
			}
		}
		if run("getent", "group", oldName) == nil {
			if err := run("groupmod", "-n", newName, oldName); err != nil {
				log(fmt.Sprintf("  Warning: rename group %s: %v", oldName, err))
			}
		}
	}
}

// textFile reports whether a file under the config dir is one the panel
// wrote as text with paths or user names in it (never keys or certificates).
func textFile(name string) bool {
	switch {
	case name == "Caddyfile", strings.HasSuffix(name, ".json"), strings.HasSuffix(name, ".conf"):
		return true
	}
	return false
}

func rewriteTextFiles(root string) error {
	return filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil || !info.Mode().IsRegular() || !textFile(info.Name()) {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rename := RenamePaths
		if info.Name() == "wg0.conf" {
			rename = Rename // per-user routing rules name the WARP accounts
		}
		if renamed := rename(string(data)); renamed != string(data) {
			// Keep the file's mode: config.json and WARP files are private.
			return os.WriteFile(path, []byte(renamed), info.Mode().Perm())
		}
		return nil
	})
}

// renameFiles renames the panel's own files in dir, rewriting their content.
func renameFiles(dir string) error {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, e := range entries {
		if !e.Type().IsRegular() || !strings.HasPrefix(e.Name(), legacy+"-") {
			continue
		}
		oldPath := filepath.Join(dir, e.Name())
		data, err := os.ReadFile(oldPath)
		if err != nil {
			return err
		}
		info, err := e.Info()
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, Rename(e.Name())), []byte(Rename(string(data))), info.Mode().Perm()); err != nil {
			return err
		}
		if err := os.Remove(oldPath); err != nil {
			return err
		}
	}
	return nil
}

// moveBinary installs the running binary as rovunet and removes the old
// command. Removing a running executable is safe on Linux.
func moveBinary() error {
	oldPath := filepath.Join(BinDir, legacy)
	if _, err := os.Stat(oldPath); err != nil {
		return nil
	}
	newPath := filepath.Join(BinDir, "rovunet")
	if _, err := os.Stat(newPath); os.IsNotExist(err) {
		if err := copyExecutable(oldPath, newPath); err != nil {
			return err
		}
	}
	return os.Remove(oldPath)
}

func copyExecutable(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	tmp := dst + ".tmp"
	if err := os.WriteFile(tmp, data, 0755); err != nil {
		return err
	}
	return os.Rename(tmp, dst)
}

func run(name string, args ...string) error {
	return exec.Command(name, args...).Run()
}

// migrateSSHConfig updates the panel's sshd_config blocks to the renamed
// group through system.EnsureSSHConfig, which validates with sshd -t before
// replacing the live file. A server without the panel's blocks is untouched.
func migrateSSHConfig() error {
	data, err := os.ReadFile("/etc/ssh/sshd_config")
	if err != nil {
		return nil
	}
	if !strings.Contains(string(data), "Match Group "+legacy+"-ssh") {
		return nil
	}
	return system.EnsureSSHConfig()
}
